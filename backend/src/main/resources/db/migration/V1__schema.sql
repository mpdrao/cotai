-- cotai schema, aligned with the Astah object model (cotai - modelo de objeto).
-- Money is always BIGINT cents. All timestamps are UTC (timestamptz).

CREATE TABLE organizer (
    id            UUID PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL
);
CREATE UNIQUE INDEX uq_organizer_email ON organizer (lower(email));

-- Event: the catalog entry. event_code is the optional self relationship (Event -> Event 0..1);
-- gift_list_id is the Event -> GiftList relationship (added after gift_list exists).
CREATE TABLE event (
    code                            VARCHAR(30) PRIMARY KEY,
    name                            VARCHAR(60) NOT NULL,
    default_reservation_ttl_minutes INT         NOT NULL CHECK (default_reservation_ttl_minutes BETWEEN 10 AND 1440),
    event_code                      VARCHAR(30) REFERENCES event (code) ON DELETE SET NULL,
    gift_list_id                    UUID
);
CREATE INDEX ix_event_event_code ON event (event_code);

CREATE TABLE gift_list (
    id                      UUID PRIMARY KEY,
    owner_id                UUID         NOT NULL REFERENCES organizer (id),
    event_code              VARCHAR(30)  NOT NULL REFERENCES event (code),
    title                   VARCHAR(80)  NOT NULL,
    slug                    VARCHAR(100) NOT NULL,
    event_date              DATE         NOT NULL,
    status                  VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    reservation_ttl_minutes INT          NOT NULL CHECK (reservation_ttl_minutes BETWEEN 10 AND 1440),
    created_at              TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_gift_list_slug UNIQUE (slug)
);
CREATE INDEX ix_gift_list_owner ON gift_list (owner_id);

ALTER TABLE event ADD CONSTRAINT fk_event_gift_list FOREIGN KEY (gift_list_id) REFERENCES gift_list (id) ON DELETE SET NULL;
CREATE INDEX ix_event_gift_list_id ON event (gift_list_id);

-- Item belongs to a GiftList (composition) and/or is offered by an Event (aggregation, is_default).
CREATE TABLE item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gift_list_id     UUID REFERENCES gift_list (id),
    event_code       VARCHAR(30) REFERENCES event (code),
    name             VARCHAR(80) NOT NULL,
    unit             VARCHAR(30) NOT NULL,
    unit_price_cents BIGINT      NOT NULL CHECK (unit_price_cents >= 1),
    archived         BOOLEAN     NOT NULL DEFAULT FALSE,
    image_url        TEXT,
    is_default       BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_item_gift_list ON item (gift_list_id);

CREATE TABLE payment (
    id                 UUID PRIMARY KEY,
    provider           VARCHAR(30)  NOT NULL,
    provider_reference VARCHAR(80),
    amount_cents       BIGINT       NOT NULL CHECK (amount_cents >= 1),
    status             VARCHAR(20)  NOT NULL
        CHECK (status IN ('CREATED', 'PENDING', 'PAID', 'DECLINED', 'EXPIRED', 'FAILED')),
    checkout_url       VARCHAR(500),
    qr_code_payload    VARCHAR(500),
    expires_at         TIMESTAMPTZ  NOT NULL,
    paid_at            TIMESTAMPTZ,
    CONSTRAINT uq_payment_provider_reference UNIQUE (provider_reference)
);

CREATE TABLE reservation (
    id                UUID PRIMARY KEY,
    item_id           BIGINT       NOT NULL REFERENCES item (id),
    payment_id        UUID REFERENCES payment (id),
    guest_name        VARCHAR(80)  NOT NULL,
    guest_email       VARCHAR(254) NOT NULL,
    quantity          INT          NOT NULL CHECK (quantity >= 1),
    unit_price_cents  BIGINT       NOT NULL CHECK (unit_price_cents >= 1),
    amount_cents      BIGINT       NOT NULL,
    status            VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    manage_token_hash VARCHAR(64)  NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL,
    closed_at         TIMESTAMPTZ,
    CONSTRAINT uq_reservation_payment UNIQUE (payment_id),
    CONSTRAINT ck_reservation_amount CHECK (amount_cents = quantity * unit_price_cents)
);
CREATE UNIQUE INDEX uq_reservation_manage_token_hash ON reservation (manage_token_hash);
CREATE INDEX ix_reservation_item ON reservation (item_id);
