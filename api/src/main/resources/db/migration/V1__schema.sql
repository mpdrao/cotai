-- cotai schema. Money is always BIGINT cents. All timestamps are UTC (timestamptz).

CREATE TABLE organizer (
    id            UUID PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL
);
CREATE UNIQUE INDEX uq_organizer_email ON organizer (lower(email));

CREATE TABLE event_type (
    code                            VARCHAR(30) PRIMARY KEY,
    name                            VARCHAR(60) NOT NULL,
    default_reservation_ttl_minutes INT         NOT NULL CHECK (default_reservation_ttl_minutes BETWEEN 10 AND 1440)
);

CREATE TABLE template_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type_code  VARCHAR(30) NOT NULL REFERENCES event_type (code),
    position         INT         NOT NULL CHECK (position BETWEEN 1 AND 10),
    name             VARCHAR(80) NOT NULL,
    unit             VARCHAR(30) NOT NULL,
    unit_price_cents BIGINT      NOT NULL CHECK (unit_price_cents >= 1),
    suggested_quotas INT         NOT NULL CHECK (suggested_quotas >= 1),
    CONSTRAINT uq_template_item_position UNIQUE (event_type_code, position)
);

CREATE TABLE gift_list (
    id                      UUID PRIMARY KEY,
    owner_id                UUID         NOT NULL REFERENCES organizer (id),
    event_type_code         VARCHAR(30)  NOT NULL REFERENCES event_type (code),
    title                   VARCHAR(80)  NOT NULL,
    slug                    VARCHAR(100) NOT NULL,
    event_date              DATE         NOT NULL,
    status                  VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    reservation_ttl_minutes INT          NOT NULL CHECK (reservation_ttl_minutes BETWEEN 10 AND 1440),
    created_at              TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_gift_list_slug UNIQUE (slug)
);
CREATE INDEX ix_gift_list_owner ON gift_list (owner_id);

CREATE TABLE item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gift_list_id     UUID        NOT NULL REFERENCES gift_list (id),
    name             VARCHAR(80) NOT NULL,
    unit             VARCHAR(30) NOT NULL,
    unit_price_cents BIGINT      NOT NULL CHECK (unit_price_cents >= 1),
    total_quotas     INT         NOT NULL CHECK (total_quotas >= 1),
    archived         BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_item_gift_list ON item (gift_list_id);

CREATE TABLE reservation (
    id                UUID PRIMARY KEY,
    item_id           BIGINT       NOT NULL REFERENCES item (id),
    guest_name        VARCHAR(80)  NOT NULL,
    guest_email       VARCHAR(254) NOT NULL,
    quantity          INT          NOT NULL CHECK (quantity >= 1),
    unit_price_cents  BIGINT       NOT NULL CHECK (unit_price_cents >= 1),
    amount_cents      BIGINT       NOT NULL,
    status            VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    manage_token_hash VARCHAR(64)  NOT NULL,
    idempotency_key   UUID         NOT NULL,
    request_hash      VARCHAR(64)  NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL,
    expires_at        TIMESTAMPTZ  NOT NULL,
    closed_at         TIMESTAMPTZ,
    CONSTRAINT uq_reservation_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_reservation_amount CHECK (amount_cents = quantity * unit_price_cents)
);
CREATE INDEX ix_reservation_item_status ON reservation (item_id, status, expires_at);
CREATE INDEX ix_reservation_pending_expiry ON reservation (expires_at) WHERE status = 'PENDING';

CREATE TABLE payment (
    id                 UUID PRIMARY KEY,
    reservation_id     UUID         NOT NULL REFERENCES reservation (id),
    provider           VARCHAR(30)  NOT NULL,
    provider_reference VARCHAR(80),
    amount_cents       BIGINT       NOT NULL CHECK (amount_cents >= 1),
    status             VARCHAR(20)  NOT NULL
        CHECK (status IN ('CREATED', 'PENDING', 'PAID', 'DECLINED', 'EXPIRED', 'FAILED', 'REFUND_REQUIRED')),
    checkout_url       VARCHAR(500),
    qr_code_payload    VARCHAR(500),
    expires_at         TIMESTAMPTZ  NOT NULL,
    paid_at            TIMESTAMPTZ,
    CONSTRAINT uq_payment_reservation UNIQUE (reservation_id),
    CONSTRAINT uq_payment_provider_reference UNIQUE (provider_reference)
);

CREATE TABLE payment_notification (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id        UUID REFERENCES payment (id),
    provider_event_id VARCHAR(100) NOT NULL,
    event_type        VARCHAR(40)  NOT NULL,
    raw_payload       TEXT         NOT NULL,
    outcome           VARCHAR(20)  NOT NULL CHECK (outcome IN ('APPLIED', 'DUPLICATE', 'LATE_PAYMENT', 'REJECTED')),
    received_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_payment_notification_event UNIQUE (provider_event_id)
);
